#!/bin/bash
# Kit showcase: render a kit on its own BEFORE any chapter uses it (the kit pattern, src/kits/).
# usage: scripts/kit.sh <kit> [scale=0.4]
#   needs src/kits/<kit>/showcase.tsx exporting
#     export const SHOWCASE_SEC = 6;              // length of the morph
#     export const Showcase: React.FC = () => ... // the kit swept through its parameter(s):
#                                                 // useCurrentFrame() 0..SHOWCASE_SEC*FPS-1
#   -> out/kits/<kit>/morph.mp4 + sheet.jpg (8 tiles evenly spread over the morph: the key states)
# The generated entry (src/film/preview/kit-<kit>.ts, git-ignored) draws the film's dark
# backdrop behind the kit, so read the sheet at phone size like a chapter. nice -n 15, one at a time.
set -e
cd "$(dirname "$0")/.."
source ~/.nvm/nvm.sh >/dev/null 2>&1 || true
KIT=$1; SCALE=${2:-0.4}
[[ "$KIT" =~ ^[a-z][a-z0-9-]*$ ]] || { echo "usage: $0 <kit> [scale]" >&2; exit 1; }
[ -f "src/kits/$KIT/showcase.tsx" ] || { echo "src/kits/$KIT/showcase.tsx is missing: export SHOWCASE_SEC and Showcase (see the header of this script)" >&2; exit 1; }
mkdir -p src/film/preview
ENTRY=src/film/preview/kit-$KIT.ts
cat > "$ENTRY" <<TS
// GENERATED by scripts/kit.sh. Do not edit; re-run the script instead.
import React from "react";
import { AbsoluteFill, Composition, registerRoot } from "remotion";
import { C } from "../../theme/colors";
import { FPS, HEIGHT, WIDTH } from "../../theme/layout";
import { SHOWCASE_SEC, Showcase } from "../../kits/$KIT/showcase";

const Stage: React.FC = () =>
  React.createElement(
    AbsoluteFill,
    { style: { background: \`radial-gradient(120% 80% at 50% 45%, \${C.bg1} 0%, \${C.bg0} 70%)\` } },
    React.createElement(Showcase),
  );

registerRoot(() =>
  React.createElement(Composition, {
    id: "Showcase",
    component: Stage,
    durationInFrames: Math.round(SHOWCASE_SEC * FPS),
    fps: FPS,
    width: WIDTH,
    height: HEIGHT,
  }),
);
TS
D=out/kits/$KIT; mkdir -p "$D"
start=$(date +%s)
nice -n 15 npx remotion render "$ENTRY" Showcase "$D/morph.mp4" --scale="$SCALE" --concurrency=4 --log=error
echo "render took $(( $(date +%s) - start ))s"
N=$(ffprobe -v error -select_streams v:0 -count_packets -show_entries stream=nb_read_packets -of csv=p=0 "$D/morph.mp4")
STEP=$(( (N - 1) / 7 )); [ "$STEP" -ge 1 ] || STEP=1
ffmpeg -y -loglevel error -i "$D/morph.mp4" \
  -vf "select='not(mod(n\,$STEP))',scale=270:-1,tile=8x1:padding=6:color=white" -frames:v 1 "$D/sheet.jpg"
echo "wrote $D/morph.mp4 ($N frames) and $D/sheet.jpg (tile k = frame $STEP*k)"
