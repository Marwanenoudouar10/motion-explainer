"""Read and write the project's timing files from Python (shared by the audio, QA and pack scripts).

  ROOT                      project root (two levels above this file)
  fps(), transition()       FPS (src/theme/layout.ts) and TRANSITION frames (src/theme/timeline.ts)
  chapters()                [{id, title, dur, tr}] from src/film/chapters.ts, in film order
  starts(chs)               {id: global start frame}, same maths as layoutTimeline() in TS
  lines()                   {id: [{text, start, words}]} from CHAPTER_LINES in src/film/data/lines.ts
                            (words = PLANNED onsets, spread by length exactly like line() in TS)
  words_of(lines, id)       every caption word of a chapter, in order
  vo_timing()               the current src/film/data/voTiming.ts as a dict ({} if empty)
  write_vo_timing(out)      write voTiming.ts (chapter-local seconds)
  write_vo_words(out, ln)   write briefs/vo-words.md (the word table builders sync beats to)
  apply_durations(new)      set durationSec of chapters in chapters.ts: {id: seconds}
The TS files are parsed with regexes, so keep their layout: one chapter per line in CHAPTERS,
`  C01: [` blocks of `line([["text", from, to], ...])` in CHAPTER_LINES, no `"` inside texts.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CHAPTERS_TS = os.path.join(ROOT, "src", "film", "chapters.ts")
LINES_TS = os.path.join(ROOT, "src", "film", "data", "lines.ts")
VO_TS = os.path.join(ROOT, "src", "film", "data", "voTiming.ts")
VO_MD = os.path.join(ROOT, "briefs", "vo-words.md")
HEADER = (
    "// GENERATED by scripts/audio/vo_split.py from the narration take. Do not edit.\n"
    "// Chapter-LOCAL seconds. clipAt = where the chapter's clip starts; per line: start/end of\n"
    "// speech and each word's start (same word order as the caption text in lines.ts).\n"
    "export type VoLine = { start: number; end: number; words: number[] };\n"
    "export const VO_TIMING: Record<string, { src: string; clipAt: number; lines: VoLine[] }> = ")


def _read(path):
    with open(path) as f:
        return f.read()


def fps():
    m = re.search(r"export const FPS = (\d+)", _read(os.path.join(ROOT, "src", "theme", "layout.ts")))
    return int(m.group(1)) if m else 30


def transition():
    m = re.search(r"export const TRANSITION = (\d+)", _read(os.path.join(ROOT, "src", "theme", "timeline.ts")))
    return int(m.group(1)) if m else 15


def chapters():
    src = _read(CHAPTERS_TS)
    body = src[src.index("export const CHAPTERS"):src.index("] as const")]
    rows = re.findall(r'id: "(\w+)", title: "([^"]*)", durationSec: ([\d.]+), transition: "(\w+)"', body)
    return [{"id": i, "title": t, "dur": float(d), "tr": tr} for i, t, d, tr in rows]


def starts(chs):
    out, t, f, tr = {}, 0, fps(), transition()
    for k, c in enumerate(chs):
        t -= tr if k > 0 and c["tr"] != "cut" else 0
        out[c["id"]] = t
        t += round(c["dur"] * f)
    return out


def lines():
    src = _read(LINES_TS)
    body = src[src.index("export const CHAPTER_LINES"):]
    body = body[:body.index("\n};")]
    out = {}
    heads = list(re.finditer(r"\n  ([A-Za-z]\w*): \[", body))
    for k, m in enumerate(heads):
        block = body[m.end(): heads[k + 1].start() if k + 1 < len(heads) else len(body)]
        lns = []
        for chunk in block.split("line(")[1:]:
            ph = re.findall(r'\["([^"]+)",\s*([\d.]+)(?:,\s*([\d.]+))?\]', chunk)
            if ph:
                lns.append({"text": " ".join(p[0] for p in ph), "start": float(ph[0][1]), "words": _planned(ph)})
        out[m.group(1)] = lns
    return out


def _planned(ph):
    """Planned word onsets of one line, the same maths as line() in lines.ts."""
    out = []
    for text, a, b in ph:
        a = float(a)
        b = float(b) if b else a
        toks = text.split(" ")
        total = sum(len(w) + 2 for w in toks)
        acc = 0
        for w in toks:
            out.append(round(a + (b - a) * acc / total, 2))
            acc += len(w) + 2
    return out


def words_of(lns, cid):
    return [w for ln in lns[cid] for w in ln["text"].split(" ")]


def vo_timing():
    src = _read(VO_TS)
    body = src[src.index("> = ") + 4:src.rindex(";")]
    return json.loads(body)


def write_vo_timing(out):
    with open(VO_TS, "w") as f:
        f.write(HEADER + json.dumps(out, indent=1) + ";\n")


def write_vo_words(out, lns):
    md = ["# Real voice timings (chapter-LOCAL seconds), generated by scripts/audio/vo_split.py", "",
          "Sync beats to these: each `// sync: \"<word>\"` beat in a chapter's beats.ts lands on (or just",
          "before) its word. Onsets are measured in each chapter's own clip (whisper guide snapped to the",
          "energy envelope; overrides from briefs/vo-fix.json are marked H). A line ends at its last sound."]
    for cid, v in out.items():
        md += ["", f"## {cid}"]
        for i, (ln, vl) in enumerate(zip(lns[cid], v["lines"])):
            ws = "  ".join(f"{w} {t:.2f}" for w, t in zip(ln["text"].split(" "), vl["words"]))
            md.append(f"- line {i + 1} ({vl['start']:.2f}-{vl['end']:.2f}s): {ws}")
    os.makedirs(os.path.dirname(VO_MD), exist_ok=True)
    with open(VO_MD, "w") as f:
        f.write("\n".join(md) + "\n")


def apply_durations(new):
    src = _read(CHAPTERS_TS)
    for cid, sec in new.items():
        src = re.sub(rf'(id: "{cid}".*?durationSec: )[\d.]+', rf"\g<1>{sec}", src, count=1)
    with open(CHAPTERS_TS, "w") as f:
        f.write(src)
