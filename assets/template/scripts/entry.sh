#!/bin/bash
# (Re)generate the isolated preview entry src/film/preview/<id>.ts for one chapter.
# It imports ONLY that chapter (or the placeholder if the chapter folder has no index.tsx
# yet), so another chapter's broken files can never break this preview. Git-ignored.
# usage: scripts/entry.sh C05      (prints the entry path; preview.sh and frame.sh call it)
set -e
cd "$(dirname "$0")/.."
ID=$1
[[ "$ID" =~ ^[A-Za-z][A-Za-z0-9_]*$ ]] || { echo "usage: $0 <ChapterId, e.g. C05>" >&2; exit 1; }
grep -q "id: \"$ID\"" src/film/chapters.ts || { echo "unknown chapter $ID (not in src/film/chapters.ts)" >&2; exit 1; }
mkdir -p src/film/preview
ENTRY=src/film/preview/$ID.ts
if [ -f "src/film/chapters/$ID/index.tsx" ] || [ -f "src/film/chapters/$ID/index.ts" ]; then
  cat > "$ENTRY" <<TS
// GENERATED by scripts/entry.sh. Do not edit; re-run the script instead.
import { registerRoot } from "remotion";
import { $ID } from "../chapters/$ID";
import { makeChapterRoot } from "./makeChapterRoot";

registerRoot(makeChapterRoot("$ID", $ID));
TS
else
  cat > "$ENTRY" <<TS
// GENERATED by scripts/entry.sh. Do not edit; re-run the script instead.
// src/film/chapters/$ID/index.tsx does not exist yet -> placeholder card.
import { registerRoot } from "remotion";
import { makeChapterRoot } from "./makeChapterRoot";

registerRoot(makeChapterRoot("$ID"));
TS
fi
echo "$ENTRY"
